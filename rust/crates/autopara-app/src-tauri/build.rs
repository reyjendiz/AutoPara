use std::collections::BTreeMap;

fn main() {
    installer_strings();
    tauri_build::build();
}

/// The NSIS template (`installer/installer.nsi`) reads its Ukrainian text as `${STR_*}` defines;
/// they are written here from the one string table so the installer has no words of its own.
fn installer_strings() {
    const TABLE: &str = "../../autopara-core/i18n/uk.json";
    println!("cargo:rerun-if-changed={TABLE}");
    let table: BTreeMap<String, String> =
        serde_json::from_str(&std::fs::read_to_string(TABLE).expect("i18n/uk.json is readable"))
            .expect("i18n/uk.json is a flat object of strings");
    let mut nsh = String::from("; Generated by build.rs from i18n/uk.json; do not edit.\n");
    for (key, text) in &table {
        if key == "app_title" || key.starts_with("installer_") {
            let text = text
                .replace('$', "$$")
                .replace('"', "$\\\"")
                .replace('\n', "$\\r$\\n")
                .replace("{path}", "$APPDATA\\${PRODUCTNAME}");
            nsh.push_str(&format!("!define STR_{} \"{text}\"\n", key.to_uppercase()));
        }
    }
    std::fs::create_dir_all("gen").expect("gen/ can be created");
    std::fs::write("gen/installer-strings.nsh", nsh)
        .expect("gen/installer-strings.nsh is writable");
}
